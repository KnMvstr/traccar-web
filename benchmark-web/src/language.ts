export const translate = (language: Language, text: string) => language === 'fr' ? french[text] ?? text : text;

export function metricDescription({ language, time, cost, prompt, cumulative, tokenType }: {
  language: Language; time: boolean; cost: boolean; prompt: boolean; cumulative: boolean; tokenType: TokenType;
}) {
  const t = (text: string) => translate(language, text);
  const metric = time ? t('Duration') : cost ? t('Estimated token cost') : t('Token consumption');
  const category = t(time ? 'All token categories (time is not filtered)' : tokenLabels[tokenType]);
  const scope = t(!prompt ? 'per run · selected prompts' : cumulative ? 'cumulative selected prompts per run' : 'per prompt per run');
  return `${metric} · ${category} · ${scope}`;
}

export function readLanguage(): Language {
  try { return localStorage.getItem('benchmark-language') === 'fr' ? 'fr' : 'en'; }
  catch { return 'en'; }
}
